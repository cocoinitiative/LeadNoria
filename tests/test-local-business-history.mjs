import assert from 'node:assert/strict';
import { businessHistoryKeys, previouslySeenBusinessKeys, isNewToSavedLists } from '../src/extension/localBusinessHistory.ts';
const business = { pageId: '12345', name: 'বাংলা Furniture', destinationUrl: 'https://shop.example/Products/A' };
const old = { runId: 'old', startedAt: '2026-01-01T00:00:00Z', leads: [business] };
const current = { runId: 'current', startedAt: '2026-01-02T00:00:00Z', leads: [business] };
const future = { runId: 'future', startedAt: '2026-01-03T00:00:00Z', leads: [{pageId:'67890'}] };
const seen = previouslySeenBusinessKeys([old, current, future], current);
assert.ok(seen.has('page:12345'));
assert.ok(!seen.has('page:67890'));
assert.equal(isNewToSavedLists({ ...business, adLibraryIds:['different-ad'], name:'Renamed Business' }, seen), false);
assert.equal(isNewToSavedLists({ pageId:'67890' }, seen), true);
assert.equal(isNewToSavedLists({ name:'Only a name', phones:['+8801700000000'] }, seen), false);
assert.deepEqual(businessHistoryKeys({ name:'Seller', destinationUrl:'https://daraz.com.bd/product/a' }), []);
assert.deepEqual(businessHistoryKeys({ name:'Seller', destinationUrl:'https://facebook.com/ads/library/?id=1' }), []);
assert.ok(businessHistoryKeys({ facebookPageUrl:'https://www.facebook.com/profile.php?id=12345' }).includes('page:12345'));
assert.deepEqual(businessHistoryKeys({ facebookPageUrl:'https://facebook.com.evil.example/a' }), []);
const siteKeys = new Set(businessHistoryKeys({ name:'Bengal Furniture', destinationUrl:'https://www.shop.example/a' }));
assert.equal(isNewToSavedLists({name:'Bengal  Furniture',destinationUrl:'https://shop.example/b?utm_source=test'},siteKeys),false);
assert.equal(isNewToSavedLists({name:'Different Seller',destinationUrl:'https://shop.example/a'},siteKeys),true);
assert.equal(previouslySeenBusinessKeys([old], { ...current, startedAt:'invalid' }).size,0);
assert.equal(previouslySeenBusinessKeys([current],current).size,0);
console.log('PASS: 13 local history checks; no API or network.');
