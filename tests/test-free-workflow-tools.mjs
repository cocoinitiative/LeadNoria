import assert from 'node:assert/strict';
import { readLeadFollowup, saveLeadFollowup } from '../src/extension/leadFollowup.ts';
import { leadResultsToCsv, leadResultsToSheets } from '../src/extension/clipboard/leadSheets.ts';
import { compileResearchIntent, LeadRelevanceEngine } from '../src/extension/relevanceEngine.ts';
import { executeManualImport } from '../src/extension/manualImport/importOrchestrator.ts';
const values = new Map();
const storage = {getItem:key=>values.get(key)||null,setItem:(key,value)=>values.set(key,value)};
assert.equal(readLeadFollowup(storage,'business'),null);
saveLeadFollowup(storage,'business','CONTACTED','বাংলা note\nCall tomorrow');
assert.equal(readLeadFollowup(storage,'business').status,'CONTACTED');
assert.equal(readLeadFollowup(storage,'business').note,'বাংলা note\nCall tomorrow');
assert.throws(()=>saveLeadFollowup({setItem(){throw new Error('Quota');}},'business','NEW','Unsaved'),/Quota/);
assert.equal(readLeadFollowup(storage,'business').status,'CONTACTED');
assert.throws(()=>saveLeadFollowup(storage,'business','FAKE','bad'));
assert.throws(()=>saveLeadFollowup(storage,'business','NEW','x'.repeat(2001)));
assert.throws(()=>readLeadFollowup({getItem:()=>'{broken'},'business'));
const row = { displayName:'Furniture, "Dhaka"',isExportable:true,isRestricted:false,websiteUrl:'https://shop.example',contactSummary:{phoneText:'+8801700000000'},canonicalRecord:{sampleCopy:'বাংলা\nNew line'} };
const csv=leadResultsToCsv([row,{...row,isRestricted:true}]);
assert.ok(csv.startsWith('"Page name","Page URL","Website","Email","Phone"\r\n'));
assert.ok(csv.includes('"Furniture, ""Dhaka"""'));
assert.equal(leadResultsToSheets([row]).split('\n').length,2);
assert.equal(leadResultsToSheets([row]).split('\n')[0].split('\t').length,5);
assert.ok(!csv.includes('Ad copy'));
const intent=compileResearchIntent({mode:'CUSTOM',keywords:['furniture'],targetCountryCode:'BD',exclusions:['training']});
assert.deepEqual(intent.exclusions,['training']);
const candidate={libraryId:'885500000000001',pageName:'Dhaka Furniture Training',bodyCopy:'Furniture training course at our showroom in Dhaka, Bangladesh. Call +8801712345678.',ctaText:'Shop Now',destinationUrl:'https://training.example'};
assert.equal(LeadRelevanceEngine.evaluateCandidate(candidate,intent).decision,'NOT_RELEVANT');
const result=await executeManualImport([candidate],{keywords:['furniture'],countryCode:'BD',exclusions:['training']});
assert.ok(result.leads.every(lead=>lead.status!=='QUALIFIED'));
assert.equal(result.rejectedCount,1);
assert.ok(result.rejectedDetails[0].reason.includes('training'));
assert.deepEqual(result.run.exclusions,['training']);
const repeat=await executeManualImport([candidate],{keywords:['furniture'],countryCode:'BD',exclusions:['training']});
assert.equal(repeat.duplicateCount,1);
const changed=await executeManualImport([candidate],{keywords:['furniture'],countryCode:'BD',exclusions:[]});
assert.equal(changed.duplicateCount,0);
console.log('PASS: follow-up persistence and failures; five-column CSV/Sheets; exclusion qualification, storage, repeat and changed criteria.');
